package es.hugoalvarezajenjo.sproutstudio.ui.designsystem

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color
import es.hugoalvarezajenjo.sproutstudio.ui.designsystem.SyntaxColors

/**
 * IDE colour tokens, modelled on the JetBrains "New UI" (Int UI) palettes.
 * Every surface in the app reads from here, never from literal colours.
 */
@Immutable
data class IdeColors(
    val isDark: Boolean,
    /** Window chrome: tool windows, tab strip, status bar. */
    val panel: Color,
    /** Editor background. */
    val editor: Color,
    /** 1px separators between areas. */
    val border: Color,
    val text: Color,
    val textMuted: Color,
    val textDisabled: Color,
    val hover: Color,
    /** Selected row in a list/tree that has focus. */
    val selection: Color,
    val accent: Color,
    val onAccent: Color,
    val currentLine: Color,
    val lineNumber: Color,
    val lineNumberActive: Color,
    val error: Color,
    val errorBg: Color,
    val warning: Color,
    val success: Color,
    val popup: Color,
    val popupBorder: Color,
    val tooltip: Color,
    val onTooltip: Color,
    /** Find: every match / the selected one (IntelliJ search-result colours). */
    val findMatch: Color,
    val findCurrent: Color,
    /** Git, IntelliJ's VCS file colours: names in the tree / Commit window. */
    val vcsModified: Color,
    val vcsAdded: Color,
    val vcsDeleted: Color,
    val vcsUnversioned: Color,
    val vcsIgnored: Color,
    /** Git change bars in the editor gutter. */
    val gutterAdded: Color,
    val gutterModified: Color,
    val gutterDeleted: Color,
    val syntax: SyntaxColors,
)

